"""Conexão PostgreSQL para autenticação. Nunca imprime a DATABASE_URL."""
import os
import psycopg

SCHEMA = (
    """CREATE TABLE IF NOT EXISTS users (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      email TEXT UNIQUE NOT NULL, salt BYTEA NOT NULL, digest BYTEA NOT NULL,
      full_name TEXT, birth_date TEXT, age_verified_at TEXT,
      guardian_email TEXT, guardian_approved_at TEXT
    )""",
    """ALTER TABLE users
       ADD COLUMN IF NOT EXISTS is_admin BOOLEAN NOT NULL DEFAULT FALSE""",
    """CREATE TABLE IF NOT EXISTS sessions (
      token_hash TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id),
      expires BIGINT NOT NULL
    )""",
)

class Connection:
    def __init__(self, url):
        self.conn = psycopg.connect(url, connect_timeout=10)
        for stmt in SCHEMA:
            self.conn.execute(stmt)
        self.conn.commit()

    def execute(self, sql, params=()):
        # Queries existentes usam marcadores SQLite. Converter apenas marcadores,
        # sem interpolar valores de usuários no SQL.
        return self.conn.execute(sql.replace('?', '%s'), params)

    def commit(self):
        self.conn.commit()

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, tb):
        try:
            if exc_type: self.conn.rollback()
            else: self.conn.commit()
        finally:
            self.conn.close()

def connect():
    url = os.environ['DATABASE_URL']
    if '[YOUR-PASSWORD]' in url:
        raise RuntimeError('DATABASE_URL ainda contém o marcador de senha.')
    return Connection(url)
