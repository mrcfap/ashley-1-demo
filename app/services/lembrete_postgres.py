"""Persistência explícita de palavra-chave por conta no PostgreSQL."""
import os
import re
import unicodedata

def _norm(value):
    return ''.join(c for c in unicodedata.normalize('NFD', value.casefold()) if not unicodedata.combining(c))

def responder(usuario, mensagem):
    import psycopg
    texto = _norm(mensagem)
    palavra = bool(re.search(r'\bpalavra(?:[- ]chave)?\b', texto))
    numero = bool(re.search(r'\bnumero\b', texto))
    correcao = re.fullmatch(r'(?:coloque|troque|substitua|mude|corrija|atualize)\s+(.{1,80}?)\s+em\s+vez\s+de\s+(.{1,80})[.!?]?', mensagem.strip(), re.I)
    escrita = bool(re.search(r'\b(?:guarde|salve|registre|memorize)\b', texto))
    consulta = bool(re.search(r'\b(?:qual|quais|lembra|lembrar|recorda|recupere|diz|diga|guardei|pedi)\b', texto))
    historico = palavra and bool(re.search(r'\b(?:tres|3|historico|alteracoes|correcoes|versoes|sequencia)\b', texto))
    if not (correcao or ((palavra or numero) and (escrita or consulta))):
        return None
    with psycopg.connect(os.environ['DATABASE_URL'], connect_timeout=10) as conn:
        conn.execute("CREATE TABLE IF NOT EXISTS triad_lembrete_conta (usuario TEXT PRIMARY KEY, palavra TEXT NOT NULL DEFAULT '', numero TEXT NOT NULL DEFAULT '')")
        conn.execute('CREATE TABLE IF NOT EXISTS triad_lembrete_historico (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, usuario TEXT NOT NULL, valor TEXT NOT NULL)')
        uid = str(usuario)
        if correcao:
            novo, antigo = (v.strip(' "“”.,!?') for v in correcao.groups())
            anterior = conn.execute('SELECT palavra FROM triad_lembrete_conta WHERE usuario=%s FOR UPDATE', (uid,)).fetchone()
            if not anterior or anterior[0].casefold() != antigo.casefold():
                return 'Não alterei a palavra: o valor anterior informado não corresponde ao que está salvo.'
            conn.execute('UPDATE triad_lembrete_conta SET palavra=%s WHERE usuario=%s', (novo, uid))
            conn.execute('INSERT INTO triad_lembrete_historico(usuario,valor) VALUES (%s,%s)', (uid, novo))
            return f'Atualizei a palavra de “{antigo}” para “{novo}”.'
        if escrita:
            aspas = re.search(r'["“]([^"”\r\n]{1,80})["”]', mensagem)
            valor_palavra = aspas.group(1).strip() if palavra and aspas else ''
            match_num = re.search(r'\bnumero\s*(?:agora\s+e\s+|e\s+|para\s+|:\s*)?(-?\d{1,18})(?!\w)', texto)
            valor_numero = match_num.group(1) if numero and match_num else ''
            if palavra and not valor_palavra:
                return 'Diga a palavra que quer guardar entre aspas.'
            if numero and not valor_numero:
                return 'Informe o número que quer guardar.'
            conn.execute("INSERT INTO triad_lembrete_conta(usuario,palavra,numero) VALUES (%s,%s,%s) ON CONFLICT(usuario) DO UPDATE SET palavra=COALESCE(NULLIF(EXCLUDED.palavra,''),triad_lembrete_conta.palavra),numero=COALESCE(NULLIF(EXCLUDED.numero,''),triad_lembrete_conta.numero)", (uid, valor_palavra, valor_numero))
            if valor_palavra:
                conn.execute('INSERT INTO triad_lembrete_historico(usuario,valor) VALUES (%s,%s)', (uid, valor_palavra))
            return 'Guardei na sua conta ' + ' e '.join(x for x in (f'a palavra “{valor_palavra}”' if valor_palavra else '', f'o número {valor_numero}' if valor_numero else '') if x) + '.'
        salvo = conn.execute('SELECT palavra,numero FROM triad_lembrete_conta WHERE usuario=%s', (uid,)).fetchone()
        if historico:
            valores = [r[0] for r in conn.execute('SELECT valor FROM triad_lembrete_historico WHERE usuario=%s ORDER BY id', (uid,))]
            return 'A sequência registrada foi: ' + ' → '.join(valores) + '.' if valores else 'Não encontrei histórico de alterações da palavra nesta conta.'
        valor_palavra, valor_numero = salvo or ('', '')
        partes = []
        if palavra:
            partes.append(f'A palavra que você pediu para guardar é “{valor_palavra}”.' if valor_palavra else 'Ainda não encontrei uma palavra guardada nesta conta.')
        if numero:
            partes.append(f'O número que você pediu para guardar é {valor_numero}.' if valor_numero else 'Ainda não encontrei um número guardado nesta conta.')
        return ' '.join(partes)
