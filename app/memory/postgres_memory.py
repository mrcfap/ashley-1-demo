"""Persistência da memória longa no Supabase PostgreSQL."""

import os
import psycopg
from psycopg.rows import dict_row, tuple_row


DDL = (
    """CREATE TABLE IF NOT EXISTS memoria_longo_prazo (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id BIGINT NOT NULL,
      categoria TEXT NOT NULL,
      chave TEXT NOT NULL,
      conteudo TEXT NOT NULL,
      importancia DOUBLE PRECISION NOT NULL DEFAULT 0.7,
      permanencia DOUBLE PRECISION NOT NULL DEFAULT 0.8,
      criado_em TEXT NOT NULL,
      atualizado_em TEXT NOT NULL,
      UNIQUE(user_id, categoria, chave)
    )""",
    """CREATE TABLE IF NOT EXISTS interacoes_longo_prazo (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id BIGINT NOT NULL,
      entrada TEXT NOT NULL,
      resposta TEXT NOT NULL,
      criado_em TEXT NOT NULL
    )""",
    "CREATE INDEX IF NOT EXISTS idx_mem_lp_user ON memoria_longo_prazo(user_id)",
    "CREATE INDEX IF NOT EXISTS idx_inter_lp_user ON interacoes_longo_prazo(user_id)",
)


class Connection:
    def __init__(self):
        self.conn = psycopg.connect(
            os.environ["DATABASE_URL"],
            connect_timeout=10,
            row_factory=dict_row,
        )

    def execute(self, sql, params=()):
        sql = sql.replace("?", "%s")
        if "COUNT(*)" in sql.upper():
            cursor = self.conn.cursor(row_factory=tuple_row)
            cursor.execute(sql, params)
            return cursor
        return self.conn.execute(sql, params)

    def commit(self):
        self.conn.commit()

    def close(self):
        self.conn.close()

    def __enter__(self):
        return self

    def __exit__(self, typ, val, tb):
        try:
            if typ:
                self.conn.rollback()
            else:
                self.conn.commit()
        finally:
            self.conn.close()


def connect():
    return Connection()


def init():
    with connect() as conn:
        for sql in DDL:
            conn.execute(sql)
