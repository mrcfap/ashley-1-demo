CREATE TABLE IF NOT EXISTS public.facial_profiles (
  user_id BIGINT PRIMARY KEY REFERENCES public.users(id) ON DELETE CASCADE,
  encrypted_features BYTEA NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS public.continuum_resultados (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  tarefa_hash TEXT NOT NULL,
  grupo TEXT NOT NULL CHECK (grupo IN ('treino','inedito')),
  sucesso BOOLEAN NOT NULL,
  duracao_ms DOUBLE PRECISION NOT NULL,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_continuum_user_created ON public.continuum_resultados(user_id, criado_em DESC);
REVOKE ALL ON public.facial_profiles FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.continuum_resultados FROM PUBLIC, anon, authenticated;
